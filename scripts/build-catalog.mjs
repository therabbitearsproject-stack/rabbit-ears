// Builds catalog.json: for every built-in channel, its pool of playable videos with the file,
// length, title, year and subtitle file the page needs. With this file the page can draw the whole TV guide
// at once instead of looking up hundreds of videos at the Internet Archive one by one.
//
// Channels are read from index.html (the SAFE filter and the BUILT_IN list), so they're only
// defined in one place. Video details already in the previous catalog.json are reused, so after
// the first run only newly popular videos get looked up.
//
// Run: node scripts/build-catalog.mjs   (Node 18+; no packages needed)

import { readFile, writeFile } from "node:fs/promises";
import { buildTrekPool } from "./trek-programming.mjs";
import { commercialRow, commercialYearAllowed } from "./commercial-library.mjs";
import { loadChannelBreakLibrary } from "./channel-break-library.mjs";
import { buildPorchlightPool } from "./porchlight-programming.mjs";

const POOL = 300;          // most-downloaded matches kept per channel
const CONCURRENCY = 6;     // the Archive slows down badly when flooded
const UA = "RabbitEarsCatalog/1.0 (+https://github.com/therabbitearsproject-stack/rabbit-ears)";

// ---- channels, straight from index.html ----
const html = await readFile(new URL("../index.html", import.meta.url), "utf8");
const MediaCompatibility = new Function(await readFile(new URL("../media-compatibility.js", import.meta.url), "utf8") + ";return MediaCompatibility;")();
const safeSrc = html.match(/^const SAFE = `[^`]*`;$/m)?.[0];
const listStart = html.indexOf("const BUILT_IN = [");
const listEnd = html.indexOf("\n];", listStart);
if (!safeSrc || listStart < 0 || listEnd < 0) throw new Error("couldn't find SAFE / BUILT_IN in index.html");
const BUILT_IN = new Function(`${safeSrc}\n${html.slice(listStart, listEnd + 3)}\nreturn BUILT_IN;`)();
console.log(`${BUILT_IN.length} channels`);

// ---- previous catalog, for reuse ----
let prev = { meta: {} };
try { prev = JSON.parse(await readFile(new URL("../catalog.json", import.meta.url), "utf8")); } catch {}
const known = new Map(); // id -> row (or null when the id had no playable video)
// Rows from before subtitles were tracked (5 fields) are looked up again once.
for (const rows of Object.values(prev.pools || {})) for (const r of rows) if (r.length >= 6) known.set(r[0], r);
for (const id of prev.unplayable || []) known.set(id, null);

// ---- helpers mirroring the page's own logic ----
function parseLen(v) {
  if (v == null) return 0;
  const s = String(v);
  if (s.includes(":")) return s.split(":").reduce((a, p) => a * 60 + parseFloat(p || 0), 0);
  return parseFloat(s) || 0;
}
async function getJSON(url, tries = 3) {
  for (let i = 0; i < tries; i++) {
    try {
      const r = await fetch(url, { headers: { "User-Agent": UA }, signal: AbortSignal.timeout(30000) });
      if (r.ok) return await r.json();
      if (r.status === 404) return null;
    } catch {}
    await new Promise(res => setTimeout(res, 2000 * (i + 1)));
  }
  throw new Error("failed: " + url);
}
// The subtitle file that goes with the chosen video, or "". Most are the Archive's automatic
// speech-recognition captions ("name.asr.srt"); some items have hand-made ones.
const stem = n => n.replace(/^.*\//, "").replace(/\.(mp4|vtt|srt)$/i, "").replace(/(_512kb|\.ia)$/i, "")
                   .replace(/\.(asr|autogenerated|auto|en|eng|english)$/i, "").replace(/\.(asr|en)$/i, "").toLowerCase();
function pickSub(files, video) {
  const subs = files.filter(f => /\.(vtt|srt)$/i.test(f.name) && !/\.(es|fr|de|it|pt|ru|ja|zh|ko|ar|nl|pl|tr|sv)\.(vtt|srt)$/i.test(f.name));
  if (!subs.length) return "";
  let match = subs.filter(s => stem(s.name) === stem(video));
  const videoStems = new Set(files.filter(f => /\.mp4$/i.test(f.name)).map(f => stem(f.name)));
  if (!match.length && new Set(subs.map(s => stem(s.name))).size === 1 && videoStems.size === 1) match = subs;
  const auto = n => /\.(asr|autogenerated)\./i.test(n);
  match.sort((a, b) => auto(a.name) - auto(b.name) || (/\.vtt$/i.test(b.name) - /\.vtt$/i.test(a.name)));
  return match[0]?.name || "";
}
async function videoRow(id) {
  const d = await getJSON("https://archive.org/metadata/" + encodeURIComponent(id));
  const all = d?.files || [];
  const files = all.filter(f => /\.mp4$/i.test(f.name) && parseLen(f.length) > 5);
  files.sort((a, b) => (/h\.264/i.test(b.format) ? 1 : 0) - (/h\.264/i.test(a.format) ? 1 : 0) || a.name.localeCompare(b.name));
  const f = MediaCompatibility.choose(all, files[0]);
  if (!f) return null;
  const title = String([].concat(d.metadata?.title || id)[0]);
  const year = String([].concat(d.metadata?.year || d.metadata?.date || "")[0]).slice(0, 4);
  return [id, f.name, Math.round(parseLen(f.length) * 10) / 10, title, year, pickSub(all, f.name), "", Number(f.width) || 0, Number(f.height) || 0,
    MediaCompatibility.knownCompatible(f) ? MediaCompatibility.version : ""];
}
async function pool(fn, items) {
  const out = new Array(items.length); let next = 0;
  await Promise.all(Array.from({ length: CONCURRENCY }, async () => {
    while (next < items.length) { const i = next++; out[i] = await fn(items[i]); }
  }));
  return out;
}

// ---- build ----
const pools = {}, coverage = {}, memberships = {}, unplayable = new Set();
let looked = 0, reused = 0, failed = 0;
for (const ch of BUILT_IN) {
  if (ch.library) {
    if (ch.library === "porchlight-v1") {
      const library = JSON.parse(await readFile(new URL("./porchlight-library.json", import.meta.url), "utf8"));
      const codecs = JSON.parse(await readFile(new URL("./porchlight-codecs.json", import.meta.url), "utf8"));
      pools[ch.q] = await buildPorchlightPool(library, codecs, id => getJSON("https://archive.org/metadata/" + encodeURIComponent(id)), pickSub, prev.pools?.[ch.q]);
      console.log(`${ch.name}: ${pools[ch.q].length} reviewed episodes only`);
      continue;
    }
    if (ch.library !== "star-trek-v1") throw new Error("Unknown reviewed library: " + ch.library);
    const library = JSON.parse(await readFile(new URL("./star-trek-library.json", import.meta.url), "utf8"));
    pools[ch.q] = await buildTrekPool(library, id => getJSON("https://archive.org/metadata/" + encodeURIComponent(id)), pickSub, prev.pools?.[ch.q]);
    console.log(`${ch.name}: ${pools[ch.q].length} reviewed full programs`);
    continue;
  }
  let ids;
  try {
    const searches = ch.franchises ? [...ch.franchises.map(f => `(${ch.q}) AND (${f.q})`), ch.q] : [ch.q];
    const groups = await pool(async q => {
      const url = "https://archive.org/advancedsearch.php?q=" + encodeURIComponent(`(${q}) AND mediatype:movies`) +
                  `&fl[]=identifier&rows=${Math.floor(POOL / searches.length)}&sort[]=downloads+desc&output=json`;
      return (await getJSON(url)).response.docs.map(d => d.identifier);
    }, searches);
    ids = [...new Set(groups.flat())];
    if (ch.franchises) memberships[ch.q] = Object.fromEntries(ch.franchises.map((f, i) => [f.name, new Set(groups[i])]));
  }
  catch (e) {
    // Keep yesterday's pool rather than emptying the channel.
    if (prev.pools?.[ch.q]) { pools[ch.q] = prev.pools[ch.q]; if (prev.coverage?.[ch.q]) coverage[ch.q] = prev.coverage[ch.q]; console.log(`! ${ch.name}: search failed, kept old pool`); }
    else console.log(`! ${ch.name}: search failed`);
    continue;
  }
  const rows = await pool(async id => {
    if (known.has(id)) { reused++; return known.get(id); }
    looked++;
    try { const r = await videoRow(id); known.set(id, r); return r; }
    catch { failed++; return undefined; } // unknown this run; not marked unplayable
  }, ids);
  ids.forEach((id, i) => { if (rows[i] === null) unplayable.add(id); });
  pools[ch.q] = rows.filter(Boolean);
  console.log(`${ch.name}: ${pools[ch.q].length}/${ids.length} playable`);
}

// ---- viewer reports ("Report this tape") ----
// Tapes reported "not appropriate" twice or "won't play" three times leave every channel; tapes
// reported "wrong channel" twice leave that channel. Reports can't be tied to people, so these are
// low bars on purpose; a mistaken removal costs one video out of 300. Everything reported is listed
// in the workflow run's summary.
const nameOf = Object.fromEntries(BUILT_IN.map(c => [c.q, c.name]));
let reports = {};
try { reports = (await getJSON("https://project-rabbitears-default-rtdb.firebaseio.com/reports.json")) || {}; }
catch { console.log("! couldn't read reports"); }
const tally = new Map(); // id -> { broken, quality, wrong: {channel: n}, inappropriate, last }
for (const r of Object.values(reports)) {
  if (!r?.id || !r.reason) continue;
  const t = tally.get(r.id) || { broken: 0, quality: 0, inappropriate: 0, wrong: {}, last: 0 };
  if (r.reason === "wrong") t.wrong[r.ch] = (t.wrong[r.ch] || 0) + 1; else t[r.reason] = (t[r.reason] || 0) + 1;
  t.last = Math.max(t.last, r.t || 0);
  tally.set(r.id, t);
}
const pulled = [];
for (const [q, rows] of Object.entries(pools)) {
  pools[q] = rows.filter(([id]) => {
    const t = tally.get(id);
    if (!t) return true;
    const out = t.inappropriate >= 2 || t.broken >= 3 || (t.wrong[nameOf[q]] || 0) >= 2;
    if (out) pulled.push(`${id} (${nameOf[q]})`);
    return !out;
  });
}
if (tally.size) {
  const titleOf = id => { for (const rows of Object.values(prev.pools || {})) for (const r of rows) if (r[0] === id) return r[3]; return ""; };
  const lines = ["## Tape reports", "", "| Tape | Won't play | Picture/sound | Wrong channel | Not appropriate | Last report |", "|---|---|---|---|---|---|"];
  for (const [id, t] of [...tally].sort((a, b) => b[1].last - a[1].last))
    lines.push(`| [${(titleOf(id) || id).replace(/\|/g, "/").slice(0, 70)}](https://archive.org/details/${encodeURIComponent(id)}) | ${t.broken || ""} | ${t.quality || ""} | ${Object.entries(t.wrong).map(([c, n]) => `${c} ×${n}`).join(", ")} | ${t.inappropriate || ""} | ${t.last ? new Date(t.last).toISOString().slice(0, 10) : ""} |`);
  lines.push("", pulled.length ? `**Pulled automatically:** ${pulled.join(", ")}` : "Nothing pulled automatically.",
             "", "To block a tape everywhere for good, add its id to `BLOCKED` in index.html.");
  console.log(lines.join("\n"));
  if (process.env.GITHUB_STEP_SUMMARY) await writeFile(process.env.GITHUB_STEP_SUMMARY, lines.join("\n") + "\n", { flag: "a" });
}

for (const [q, groups] of Object.entries(memberships)) {
  coverage[q] = Object.fromEntries(Object.entries(groups).map(([name, ids]) => [name, (pools[q] || []).filter(r => ids.has(r[0])).length]));
}
let commercials = [], bumpers = [];
if (BUILT_IN.some(ch => ch.breaks)) {
  const library = JSON.parse(await readFile(new URL("./commercial-library.json", import.meta.url), "utf8"));
  commercials = (await pool(async id => {
    try { return commercialRow(id, await getJSON("https://archive.org/metadata/" + encodeURIComponent(id))); }
    catch { return prev.commercials?.find(r => r[0] === id && commercialYearAllowed(r[4])) || null; }
  }, library.ids)).filter(Boolean).filter(r => {
    const reports = tally.get(r[0]);
    return !reports || (reports.broken < 3 && reports.inappropriate < 2 && (reports.wrong["Subspace 97"] || 0) < 2);
  });
  if (commercials.length < 3) throw new Error("Not enough dated vintage commercials to publish a reliable shared schedule");
  const facts = JSON.parse(await readFile(new URL("../assets/trek-bumpers/facts.json", import.meta.url), "utf8"));
  bumpers = facts.map(f => ({ id: "bumper-" + f.id, title: f.fact, file: "assets/trek-bumpers/" + f.id + ".mp4", dur: 15, local: true }));
  for (const bumper of bumpers) await readFile(new URL("../" + bumper.file, import.meta.url));
  console.log(`${commercials.length} vintage commercials (latest ${Math.max(...commercials.map(r => Number(r[4])))}) and ${bumpers.length} original 15-second bumpers`);
}
const breakLibraries = {};
for (const id of new Set(BUILT_IN.map(ch => ch.breaks?.library).filter(Boolean))) {
  breakLibraries[id] = await loadChannelBreakLibrary(id);
  if (id === "sci-fi-channel") {
    breakLibraries[id].bumpers.push(...bumpers.map(m => ({ ...m, role: "custom-bumper" })));
  }
}
if (breakLibraries.porchlight) {
  const reserved = new Set(["CadburysCrunchieAdvert1988", "DietcokeAdvert1988", "coca-cola-advert", "tmnt-video", "disney-fantasia-vhs-advert", "sonic3mcdonaldsad", "mars-twix-a-break-from-the-norm-advert", "mc-donalds-hercules-happy-meal-commercial-1998480p", "TWAImrpovementsAdvert"]);
  breakLibraries.porchlight.commercials.push(...commercials.filter(r => reserved.has(r[0])).map(([id,file,dur,title,year]) => ({id,file,dur,title,year,role:"vintage-commercial"})),
    ...(breakLibraries["sci-fi-channel"]?.commercials || []).filter(m => m.role === "recorded-advertiser-spot"));
}
const catalog = { generated: new Date().toISOString(), pools, coverage, commercials, bumpers, breakLibraries, unplayable: [...unplayable] };
await writeFile(new URL("../catalog.json", import.meta.url), JSON.stringify(catalog));
console.log(`done: ${looked} looked up, ${reused} reused, ${failed} failed`);
